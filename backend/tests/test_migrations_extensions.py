"""Tables created by database extensions (PostGIS spatial_ref_sys) are not part of the NADIEN schema."""

from alembic import command
from sqlalchemy import create_engine, inspect

from app.database import alembic_config, init_schema, migration_filter


def _engine_with_postgis_table(tmp_path):
    engine = create_engine(f"sqlite:///{tmp_path / 'postgis.db'}")
    with engine.begin() as conn:
        conn.exec_driver_sql("CREATE TABLE spatial_ref_sys (srid INTEGER PRIMARY KEY, auth_name VARCHAR(256))")
    return engine


def test_should_report_no_changes_when_database_has_postgis_spatial_ref_sys(tmp_path):
    engine = _engine_with_postgis_table(tmp_path)
    init_schema(engine)
    with engine.begin() as conn:
        command.check(alembic_config(conn))  # raises AutogenerateDiffsDetected on a diff


def test_should_keep_spatial_ref_sys_when_migrating_a_postgis_database(tmp_path):
    engine = _engine_with_postgis_table(tmp_path)
    init_schema(engine)
    assert {"spatial_ref_sys", "alembic_version", "devices"} <= set(inspect(engine).get_table_names())


def test_should_skip_only_extension_tables_when_filtering_reflected_tables(tmp_path):
    engine = _engine_with_postgis_table(tmp_path)
    with engine.connect() as conn:
        include = migration_filter(conn)
    assert not include(None, "spatial_ref_sys", "table", True, None)
    assert include(None, "old_table_dropped_from_models", "table", True, None)
